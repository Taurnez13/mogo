ALLOWED_HTML = {"p", "br", "ul", "ol", "li", "em", "strong", "b", "i", "sup", "sub", "a", "h1", "h2", "h3",
                "h4", "h5", "h6", "blockquote", "div", "span", "cite", "q", "dl", "dt", "dd", "hr", "pre", "small", "big"}
ALLOWED_ATTRS = {"a": {"href"}}


def sanitize_html(text: str) -> Optional[etree._Element]:
    """Parse messy HTML into an XHTML-subset-safe <div> fragment, or None if it can't be parsed."""
    try:
        from lxml import html as lh
        frag = lh.fragment_fromstring(text, create_parent="div")
    except Exception:
        return None
    for el in list(frag.iter()):
        if el is frag or not isinstance(el.tag, str):
            if not isinstance(el.tag, str):
                el.drop_tag() if hasattr(el, "drop_tag") else None
            continue
        tag = el.tag.lower()
        if tag not in ALLOWED_HTML:
            el.drop_tag()  # unwrap, keep text
            continue
        el.tag = tag
        keep = ALLOWED_ATTRS.get(tag, set())
        for a in list(el.attrib):
            if a not in keep:
                del el.attrib[a]
    # lists may only contain <li>
    for lst in frag.iter("ul", "ol"):
        for ch in list(lst):
            if ch.tag != "li":
                if ch.tag == "br":
                    if ch.tail and ch.tail.strip():
                        li = etree.SubElement(lst, "li"); li.text = ch.tail
                    lst.remove(ch)
                else:
                    li = etree.Element("li"); lst.replace(ch, li); li.append(ch)
        if lst.text and lst.text.strip():
            li = etree.Element("li"); li.text = lst.text; lst.text = None; lst.insert(0, li)
    # drop empty paragraphs
    for pel in list(frag.iter("p", "div", "span")):
        if pel is not frag and len(pel) == 0 and not (pel.text or "").strip():
            pel.drop_tree() if not (pel.tail or "").strip() else pel.drop_tag()
    return frag


def _set_text(te: etree._Element, text: str, fmt: Optional[str]):
    """Put text into <Text>. HTML (fmt 02/05) is sanitised into child elements; else plain text."""
    text = (text or "").strip()
    if fmt in ("02", "05") and "<" in text:
        frag = sanitize_html(text)
        if frag is not None:
            te.text = frag.text
            for ch in list(frag):
                te.append(ch)
            return
    te.text = text


def finalise(root: etree._Element, style: str = "reference") -> etree._Element:
    """Return a properly namespaced copy of the message (reference or short tags)."""
    if style == "short":
        mp = ref_to_short()
        for e in root.iter():
            if isinstance(e.tag, str):
                e.tag = mp.get(etree.QName(e).localname, etree.QName(e).localname)
        ns = NS_SHORT
    else:
        ns = NS_REF
    xml = etree.tostring(root, encoding="unicode")
    xml = re.sub(r'^<(ONIXMessage|ONIXmessage)[^>]*>', lambda mt: mt.group(0).replace('xmlns="%s"' % NS_REF, '').replace("<%s" % mt.group(1), '<%s xmlns="%s"' % (mt.group(1), ns)), xml, count=1)
    return etree.fromstring(xml.encode("utf-8"))


def to_short_tags(root: etree._Element) -> etree._Element:
    return finalise(root, "short")


def serialise(root: etree._Element) -> bytes:
    return etree.tostring(root, xml_declaration=True, encoding="UTF-8", pretty_print=True)


_schema_cache: dict[str, etree.XMLSchema] = {}


def validate(root: etree._Element) -> list[str]:
    ns = etree.QName(root).namespace or ""
    style = "short" if ns.endswith("/short") else "reference"
    release = root.get("release", "3.0")
    key = f"{release}-{style}"
    if key not in _schema_cache:
        sd = _find_schema_dir()
        f = sd / f"xsd{release}" / f"ONIX_BookProduct_{release}_{style}.xsd"
        _schema_cache[key] = etree.XMLSchema(etree.parse(str(f)))
    xsd = _schema_cache[key]
    xsd.validate(root)
    return [f"line {e.line}: {e.message}" for e in xsd.error_log]
