"""
ONIX 3.0 exporter. Builds a reference-tag message from the database and can
emit either reference or short tags. Output is validated against the EDItEUR
schema bundled with onixcheck.
"""
from __future__ import annotations

import re
from datetime import datetime
from decimal import Decimal
from pathlib import Path
from typing import Iterable, Optional

from lxml import etree
from sqlalchemy.orm import Session

from .. import models as m
from .codelists import ref_to_short

NS_REF = "http://ns.editeur.org/onix/3.0/reference"
NS_SHORT = "http://ns.editeur.org/onix/3.0/short"
SCHEMA_DIR = Path("/usr/local/lib/python3.13/site-packages/onixcheck/schema")


def _find_schema_dir() -> Path:
    try:
        import onixcheck, os
        return Path(os.path.dirname(onixcheck.__file__)) / "schema"
    except Exception:
        return SCHEMA_DIR


class B:
    """Tiny element builder: B(parent, 'Tag', text) -> element; skips None/empty text."""

    def __init__(self, parent: etree._Element):
        self.p = parent

    def el(self, tag: str, text: Optional[object] = None, **attrs) -> Optional[etree._Element]:
        if text is None and not attrs and tag not in _EMPTY_OK:
            e = etree.SubElement(self.p, tag)
            return e
        if text is not None and str(text).strip() == "":
            return None
        e = etree.SubElement(self.p, tag, **{k: str(v) for k, v in attrs.items() if v is not None})
        if text is not None:
            if isinstance(text, Decimal):
                text = _dec(text)
            e.text = str(text)
        return e

    def opt(self, tag: str, text: Optional[object], **attrs) -> Optional[etree._Element]:
        """Only emit when text has a value."""
        if text is None or str(text).strip() == "":
            return None
        return self.el(tag, text, **attrs)

    def sub(self, tag: str) -> "B":
        return B(etree.SubElement(self.p, tag))


_EMPTY_OK = {"NoCollection", "NoContributor", "NoEdition", "MainSubject", "NoPrefix"}


def _dec(d: Decimal) -> str:
    s = f"{d.normalize():f}"
    if "." in s:
        s = s.rstrip("0").rstrip(".")
    # money always 2dp
    return s


def _money(d: Optional[Decimal]) -> Optional[str]:
    return None if d is None else f"{d:.2f}"


def _measure(d: Decimal) -> str:
    s = f"{d.normalize():f}"
    return s.rstrip("0").rstrip(".") if "." in s else s


def _split(s: Optional[str]) -> list[str]:
    return [x for x in re.split(r"[\s,;]+", s or "") if x]


class OnixExporter:
    def __init__(self, db: Session, sender_name: str, contact_name: str = "", email: str = "",
                 message_note: str = "Generated by MOGO", default_currency: str = "GBP",
                 media_base_url: Optional[str] = None, addressee_name: Optional[str] = None,
                 include_barcode: bool = False):
        self.db = db
        self.sender_name = sender_name
        self.contact_name = contact_name
        self.email = email
        self.message_note = message_note
        self.default_currency = default_currency
        self.media_base_url = (media_base_url or "").rstrip("/") or None
        self.addressee_name = addressee_name
        self.include_barcode = include_barcode

    # ------------------------------------------------------------------ #

    def build_message(self, products: Iterable[m.Product], release: str = "3.0") -> etree._Element:
        root = etree.Element("ONIXMessage", release=release)
        hb = B(root).sub("Header")
        sb = hb.sub("Sender")
        sb.el("SenderName", self.sender_name)
        sb.opt("ContactName", self.contact_name)
        sb.opt("EmailAddress", self.email)
        if self.addressee_name:
            ab = hb.sub("Addressee")
            ab.el("AddresseeName", self.addressee_name)
        hb.el("SentDateTime", datetime.utcnow().strftime("%Y%m%dT%H%M"))
        hb.opt("MessageNote", self.message_note)
        hb.el("DefaultLanguageOfText", "eng")
        hb.el("DefaultCurrencyCode", self.default_currency)
        for p in products:
            root.append(self.build_product(p))
        return root

    # ------------------------------------------------------------------ #

    def build_product(self, p: m.Product) -> etree._Element:
        pe = etree.Element("Product")
        b = B(pe)
        b.el("RecordReference", p.record_reference)
        b.el("NotificationType", p.notification_type or "03")
        b.opt("RecordSourceType", p.record_source_type or "01")
        b.el("RecordSourceName", self.sender_name)

        # Identifiers — always ensure ISBN-13 (15) and GTIN-13 (03) are present
        emitted = set()
        for i in p.identifiers:
            key = (i.id_type, i.value)
            if key in emitted:
                continue
            emitted.add(key)
            ib = b.sub("ProductIdentifier")
            ib.el("ProductIDType", i.id_type)
            ib.opt("IDTypeName", i.id_type_name)
            ib.el("IDValue", i.value)
        if p.isbn13 and ("15", p.isbn13) not in emitted:
            ib = b.sub("ProductIdentifier"); ib.el("ProductIDType", "15"); ib.el("IDValue", p.isbn13)
        if p.isbn13 and ("03", p.isbn13) not in emitted:
            ib = b.sub("ProductIdentifier"); ib.el("ProductIDType", "03"); ib.el("IDValue", p.isbn13)

        if self.include_barcode and p.isbn13 and p.product_form not in ("ED", "EA", "EB", "EC", "AJ", "AN"):
            bb = b.sub("Barcode")
            bb.el("BarcodeType", "02")       # List 141: GTIN-13
            bb.el("PositionOnProduct", "01")  # List 142: cover 4 (back cover)
        self._descriptive(b, p)
        self._collateral(b, p)
        self._publishing(b, p)
        self._related(b, p)
        self._supply(b, p)
        return pe

    # ------------------------------------------------------------------ #

    def _descriptive(self, b: B, p: m.Product):
        d = b.sub("DescriptiveDetail")
        d.el("ProductComposition", p.product_composition or "00")
        d.el("ProductForm", p.product_form or "00")
        for fd in sorted({f.code for f in p.form_details}):
            d.el("ProductFormDetail", fd)
        for ff in p.form_features:
            fb = d.sub("ProductFormFeature")
            fb.el("ProductFormFeatureType", ff.feature_type)
            fb.opt("ProductFormFeatureValue", ff.feature_value)
            fb.opt("ProductFormFeatureDescription", ff.feature_description)
        d.opt("ProductPackaging", p.product_packaging)
        d.opt("ProductFormDescription", p.product_form_description)
        d.opt("TradeCategory", p.trade_category)
        d.opt("PrimaryContentType", p.primary_content_type)
        for ms in p.measures:
            if ms.value is None or ms.value <= 0:
                continue  # schema requires > 0
            mb = d.sub("Measure")
            mb.el("MeasureType", ms.measure_type)
            mb.el("Measurement", _measure(ms.value))
            mb.el("MeasureUnitCode", ms.unit)
        d.opt("CountryOfManufacture", p.country_of_manufacture)
        for pc in p.classifications:
            cb = d.sub("ProductClassification")
            cb.el("ProductClassificationType", pc.classification_type)
            cb.el("ProductClassificationCode", pc.code)
        for pp in p.parts:
            pb = d.sub("ProductPart")
            if pp.part_isbn13:
                ib = pb.sub("ProductIdentifier"); ib.el("ProductIDType", "15"); ib.el("IDValue", pp.part_isbn13)
            pb.el("ProductForm", pp.product_form)
            pb.opt("ProductFormDescription", pp.product_form_description)
            pb.opt("NumberOfItemsOfThisForm", pp.number_of_items)
        # Collections
        if p.series_links:
            for sl in p.series_links:
                cb = d.sub("Collection")
                cb.el("CollectionType", sl.series.collection_type or "10")
                if sl.sequence_number:
                    sb = cb.sub("CollectionSequence")
                    sb.el("CollectionSequenceType", sl.sequence_type or "02")
                    sb.el("CollectionSequenceNumber", sl.sequence_number)
                tb = cb.sub("TitleDetail")
                tb.el("TitleType", "01")
                teb = tb.sub("TitleElement")
                teb.el("TitleElementLevel", "02")
                teb.el("TitleText", sl.series.title)
        else:
            d.el("NoCollection")
        # Title
        tb = d.sub("TitleDetail")
        tb.el("TitleType", p.title_type or "01")
        teb = tb.sub("TitleElement")
        teb.el("TitleElementLevel", "01")
        if p.title_prefix:
            teb.el("TitlePrefix", p.title_prefix)
            teb.el("TitleWithoutPrefix", p.title_without_prefix)
        else:
            teb.el("NoPrefix")
            teb.el("TitleWithoutPrefix", p.title_without_prefix)
        teb.opt("Subtitle", p.subtitle)
        # Contributors
        if p.contributors:
            # group multiple roles for same contributor+sequence
            grouped: dict[tuple[int, int], list[m.ProductContributor]] = {}
            for pc in p.contributors:
                grouped.setdefault((pc.sequence, pc.contributor_id), []).append(pc)
            for n, ((seq, _cid), pcs) in enumerate(sorted(grouped.items()), start=1):
                c = pcs[0].contributor
                cb = d.sub("Contributor")
                cb.el("SequenceNumber", n)
                for pc in pcs:
                    cb.el("ContributorRole", pc.role)
                if c.isni:
                    nb = cb.sub("NameIdentifier"); nb.el("NameIDType", "16"); nb.el("IDValue", c.isni)
                nb = cb.sub("NameIdentifier"); nb.el("NameIDType", "01"); nb.el("IDTypeName", f"{self.sender_name} Contributor ID"); nb.el("IDValue", str(c.id))
                if c.is_corporate or (c.corporate_name and not c.person_name):
                    cb.el("CorporateName", c.corporate_name or c.display_name)
                else:
                    cb.opt("PersonName", c.person_name)
                    cb.opt("PersonNameInverted", c.person_name_inverted)
                    cb.opt("TitlesBeforeNames", c.titles_before_names)
                    cb.opt("NamesBeforeKey", c.names_before_key)
                    cb.opt("PrefixToKey", c.prefix_to_key)
                    cb.opt("KeyNames", c.key_names)
                    cb.opt("NamesAfterKey", c.names_after_key)
                    cb.opt("SuffixToKey", c.suffix_to_key)
                    cb.opt("LettersAfterNames", c.letters_after_names)
                    cb.opt("TitlesAfterNames", c.titles_after_names)
                for af in c.affiliations:
                    ab = cb.sub("ProfessionalAffiliation")
                    ab.opt("ProfessionalPosition", af.professional_position)
                    ab.opt("Affiliation", af.affiliation)
                bio = pcs[0].biographical_note or c.biographical_note
                cb.opt("BiographicalNote", bio)
                if c.website:
                    wb = cb.sub("Website"); wb.el("WebsiteRole", "06"); wb.el("WebsiteLink", c.website)
                for pl in c.places:
                    plb = cb.sub("ContributorPlace")
                    plb.el("ContributorPlaceRelator", pl.relator)
                    plb.opt("CountryCode", pl.country_code)
                    plb.opt("RegionCode", pl.region_code)
                    plb.opt("LocationName", pl.location_name)
        else:
            d.el("NoContributor")
        d.opt("ContributorStatement", p.contributor_statement)
        # Edition
        if p.edition_type or p.edition_number or p.edition_statement:
            d.opt("EditionType", p.edition_type)
            d.opt("EditionNumber", p.edition_number)
            d.opt("EditionStatement", p.edition_statement)
        else:
            d.el("NoEdition")
        langs = p.languages or [m.Language(role="01", code="eng")]
        for lg in langs:
            lb = d.sub("Language")
            lb.el("LanguageRole", lg.role)
            lb.el("LanguageCode", lg.code)
            lb.opt("CountryCode", lg.country_code)
        for ex in p.extents:
            try:
                if Decimal(ex.value) <= 0:
                    continue  # schema requires > 0
            except Exception:
                continue
            eb = d.sub("Extent")
            eb.el("ExtentType", ex.extent_type)
            eb.el("ExtentValue", ex.value)
            eb.el("ExtentUnit", ex.unit)
        d.opt("IllustrationsNote", p.illustrations_note)
        for ac in p.ancillary_content:
            ab = d.sub("AncillaryContent")
            ab.el("AncillaryContentType", ac.content_type)
            ab.opt("AncillaryContentDescription", ac.description)
            ab.opt("Number", ac.number)
        for sj in p.subjects:
            if not (sj.code or sj.heading):
                continue
            sb = d.sub("Subject")
            if sj.main_subject:
                sb.el("MainSubject")
            sb.el("SubjectSchemeIdentifier", sj.scheme)
            if sj.scheme == "24" or sj.scheme_name:
                sb.opt("SubjectSchemeName", sj.scheme_name or self.sender_name)
            sb.opt("SubjectSchemeVersion", sj.scheme_version)
            sb.opt("SubjectCode", sj.code)
            sb.opt("SubjectHeadingText", sj.heading)
        auds = p.audiences or [m.Audience(code_type="01", code_value="01")]
        for au in auds:
            ab = d.sub("Audience")
            ab.el("AudienceCodeType", au.code_type)
            ab.el("AudienceCodeValue", au.code_value)
        for ar in p.audience_ranges:
            rb = d.sub("AudienceRange")
            rb.el("AudienceRangeQualifier", ar.qualifier)
            if ar.precision_from:
                rb.el("AudienceRangePrecision", ar.precision_from); rb.el("AudienceRangeValue", ar.value_from)
            if ar.precision_to:
                rb.el("AudienceRangePrecision", ar.precision_to); rb.el("AudienceRangeValue", ar.value_to)

    # ------------------------------------------------------------------ #

    def _collateral(self, b: B, p: m.Product):
        if not p.texts and not p.resources:
            return
        c = b.sub("CollateralDetail")
        for tc in p.texts:
            tb = c.sub("TextContent")
            tb.el("TextType", tc.text_type)
            tb.el("ContentAudience", tc.content_audience or "00")
            te = tb.el("Text", None, textformat=tc.text_format or "02")
            _set_text(te, tc.text, tc.text_format)
            tb.opt("TextAuthor", tc.text_author)
            tb.opt("SourceTitle", tc.source_title)
        for sr in p.resources:
            link = self._resource_url(sr)
            if not link:
                continue
            rb = c.sub("SupportingResource")
            rb.el("ResourceContentType", sr.content_type)
            rb.el("ContentAudience", sr.content_audience or "00")
            rb.el("ResourceMode", sr.resource_mode or "03")
            vb = rb.sub("ResourceVersion")
            vb.el("ResourceForm", sr.resource_form or "02")
            if sr.file_format:
                fb = vb.sub("ResourceVersionFeature"); fb.el("ResourceVersionFeatureType", "01"); fb.el("FeatureValue", sr.file_format)
            fname = sr.filename or link.rsplit("/", 1)[-1]
            if fname:
                fb = vb.sub("ResourceVersionFeature"); fb.el("ResourceVersionFeatureType", "04"); fb.el("FeatureValue", fname)
            vb.el("ResourceLink", link)
            if sr.content_date:
                db_ = vb.sub("ContentDate")
                db_.el("ContentDateRole", sr.content_date_role or "17")
                db_.el("Date", sr.content_date.strftime("%Y%m%d"), dateformat="00")

    def _resource_url(self, sr: m.SupportingResource) -> Optional[str]:
        if sr.local_path and self.media_base_url:
            return f"{self.media_base_url}/{sr.local_path.lstrip('/')}"
        return sr.remote_url

    # ------------------------------------------------------------------ #

    def _publishing(self, b: B, p: m.Product):
        pb = b.sub("PublishingDetail")
        if p.imprint_name:
            ib = pb.sub("Imprint"); ib.el("ImprintName", p.imprint_name)
        pubs = p.publishers or [m.Publisher(role="01", name=self.sender_name)]
        for pub in pubs:
            ub = pb.sub("Publisher")
            ub.el("PublishingRole", pub.role or "01")
            ub.el("PublisherName", pub.name)
            if pub.website:
                wb = ub.sub("Website"); wb.el("WebsiteRole", pub.website_role or "01"); wb.el("WebsiteLink", pub.website)
        pb.opt("CityOfPublication", p.city_of_publication)
        pb.opt("CountryOfPublication", p.country_of_publication)
        pb.el("PublishingStatus", p.publishing_status or "02")
        dates = list(p.publishing_dates)
        if not any(d.role == "01" for d in dates) and p.publication_date:
            dates.insert(0, m.PublishingDate(role="01", date_format="00", value=p.publication_date.strftime("%Y%m%d")))
        for d in dates:
            db_ = pb.sub("PublishingDate")
            db_.el("PublishingDateRole", d.role)
            db_.el("Date", d.value, dateformat=d.date_format or "00")
        if p.copyright_year:
            cb = pb.sub("CopyrightStatement")
            cb.el("CopyrightType", "C")
            for y in _split(p.copyright_year):
                cb.el("CopyrightYear", y)
        rights = p.sales_rights or [m.SalesRights(rights_type="01", regions_included="WORLD")]
        for sr in rights:
            sb = pb.sub("SalesRights")
            sb.el("SalesRightsType", sr.rights_type)
            tb = sb.sub("Territory")
            tb.opt("CountriesIncluded", sr.countries_included)
            tb.opt("RegionsIncluded", sr.regions_included)
            tb.opt("CountriesExcluded", sr.countries_excluded)
            tb.opt("RegionsExcluded", sr.regions_excluded)
        pb.opt("ROWSalesRightsType", p.row_sales_rights_type)

    # ------------------------------------------------------------------ #

    def _related(self, b: B, p: m.Product):
        if not p.related_works and not p.related_products:
            return
        rb = b.sub("RelatedMaterial")
        for rw in p.related_works:
            wb = rb.sub("RelatedWork")
            wb.el("WorkRelationCode", rw.relation_code)
            ib = wb.sub("WorkIdentifier")
            ib.el("WorkIDType", rw.id_type)
            ib.opt("IDTypeName", rw.id_type_name)
            ib.el("IDValue", rw.value)
        for rp in p.related_products:
            if not rp.isbn13 and not rp.other_identifiers:
                continue
            pb = rb.sub("RelatedProduct")
            for code in _split(rp.relation_codes) or ["06"]:
                pb.el("ProductRelationCode", code)
            if rp.isbn13:
                ib = pb.sub("ProductIdentifier"); ib.el("ProductIDType", "15"); ib.el("IDValue", rp.isbn13)
                ib = pb.sub("ProductIdentifier"); ib.el("ProductIDType", "03"); ib.el("IDValue", rp.isbn13)
            for oi in rp.other_identifiers or []:
                if oi.get("type") and oi.get("value"):
                    ib = pb.sub("ProductIdentifier"); ib.el("ProductIDType", oi["type"]); ib.opt("IDTypeName", oi.get("name")); ib.el("IDValue", oi["value"])
            pb.opt("ProductForm", rp.product_form)
            pb.opt("ProductFormDetail", rp.product_form_detail)

    # ------------------------------------------------------------------ #

    def _supply(self, b: B, p: m.Product):
        for sd in p.supply_details:
            ps = b.sub("ProductSupply")
            if sd.market_countries or sd.market_regions:
                mb = ps.sub("Market").sub("Territory")
                mb.opt("CountriesIncluded", sd.market_countries)
                mb.opt("RegionsIncluded", sd.market_regions)
            if sd.market_publishing_status or sd.promotion_campaign:
                mp = ps.sub("MarketPublishingDetail")
                mp.opt("MarketPublishingStatus", sd.market_publishing_status)
                mp.opt("PromotionCampaign", sd.promotion_campaign)
            sb = ps.sub("SupplyDetail")
            sup = sd.supplier
            ub = sb.sub("Supplier")
            ub.el("SupplierRole", sup.role or "01")
            if sup.id_value:
                ib = ub.sub("SupplierIdentifier"); ib.el("SupplierIDType", sup.id_type or "01"); ib.opt("IDTypeName", sup.id_type_name); ib.el("IDValue", sup.id_value)
            ub.el("SupplierName", sup.name)
            ub.opt("TelephoneNumber", sup.telephone)
            ub.opt("EmailAddress", sup.email)
            if sup.website:
                wb = ub.sub("Website"); wb.el("WebsiteRole", sup.website_role or "01"); wb.el("WebsiteLink", sup.website)
            sb.el("ProductAvailability", sd.availability or "20")
            for sdt in sd.supply_dates:
                db_ = sb.sub("SupplyDate"); db_.el("SupplyDateRole", sdt.role); db_.el("Date", sdt.value, dateformat=sdt.date_format or "00")
            sb.opt("PackQuantity", sd.pack_quantity)
            if not sd.prices:
                sb.el("UnpricedItemType", "01")
            for pr in sd.prices:
                prb = sb.sub("Price")
                prb.el("PriceType", pr.price_type)
                prb.opt("PriceStatus", pr.price_status)
                prb.el("PriceAmount", _money(pr.amount))
                if pr.tax_rate_code or pr.tax_rate_percent is not None:
                    tb = prb.sub("Tax")
                    tb.el("TaxType", "01")
                    tb.opt("TaxRateCode", pr.tax_rate_code)
                    if pr.tax_rate_percent is not None:
                        tb.el("TaxRatePercent", _measure(pr.tax_rate_percent))
                    tb.opt("TaxableAmount", _money(pr.taxable_amount))
                    tb.opt("TaxAmount", _money(pr.tax_amount))
                prb.el("CurrencyCode", pr.currency or "GBP")
                if pr.countries_included or pr.regions_included:
                    tb = prb.sub("Territory")
                    tb.opt("CountriesIncluded", pr.countries_included)
                    tb.opt("RegionsIncluded", pr.regions_included)


